//! ROS node bridge config generation (Task B3).
//!
//! `host init` exports the camera/stream lists + token path as `ros_bridge.yaml`; ROS
//! nodes (stitch/vision) subscribe FrameBus topics from this file - one source of
//! truth, no hand-written topic names/token paths on the ROS side (D-H7/D-H14 enh. 2).

/// Generate ros_bridge.yaml text (hand-built, fixed structure, no yaml dependency).
///
/// Fixed topic naming: `camera/<camera-id>`, `vision/<camera-id>` (mirrors camera id),
/// `stream/<stream-id>`. `token_path` written verbatim (caller ensures the absolute path).
pub fn ros_bridge(cameras: &[String], streams: &[String], token_path: &str) -> String {
    let mut out = String::from(
        "# Generated by host init - single source of truth for ROS node config (do not edit)\n",
    );
    out.push_str(&format!("token_path: {token_path}\n"));
    out.push_str("topics:\n");
    push_section(&mut out, "camera", cameras.iter().map(|id| format!("camera/{id}")));
    push_section(&mut out, "vision", cameras.iter().map(|id| format!("vision/{id}")));
    push_section(&mut out, "stream", streams.iter().map(|id| format!("stream/{id}")));
    out
}

fn push_section(out: &mut String, name: &str, topics: impl Iterator<Item = String>) {
    out.push_str(&format!("  {name}:\n"));
    for topic in topics {
        out.push_str(&format!("    - {topic}\n"));
    }
}
