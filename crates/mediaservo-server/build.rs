//! Build script for embedded web-app static files.
//!
//! Embeds the dist/ contents of the www apps into the binary at compile time
//! (include_bytes!), so the runtime needs NO filesystem dependency on dist.
//! This fixes the prod-image flaw where ADMIN_DIST_DIR pointed at an absolute
//! build-time path (/workspace/...) that doesn't exist in the runtime image.
//! P3-3: the voice app embeds with the same posture (optional — an absent
//! dist warns but does not fail, ponytail).

#[cfg(feature = "admin-dashboard")]
use std::{fs, path::PathBuf};

fn main() {
    // Only process when admin-dashboard feature is enabled (the web-apps embed feature)
    #[cfg(feature = "admin-dashboard")]
    {
        embed_dist("admin", "../../www/apps/admin/dist", "embedded_admin_dist.rs");
        // P3-3 voice app: same embed posture; optional like admin.
        embed_dist("voice", "../../www/apps/voice/dist", "embedded_voice_dist.rs");
    }
    #[cfg(not(feature = "admin-dashboard"))]
    {
        // No-op when feature is disabled
    }
}

/// Generate `OUT_DIR/<gen_name>` embedding all files under `dist_rel` as
/// `pub static FILES: &[(&str, &[u8])]` (relative path → include_bytes!).
#[cfg(feature = "admin-dashboard")]
fn embed_dist(app: &'static str, dist_rel: &'static str, gen_name: &'static str) {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dist_dir = manifest_dir.join(dist_rel);
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());

    if !dist_dir.exists() {
        // ponytail: warn but don't fail — the SPA is optional
        println!(
            "cargo:warning={app} dist/ not found at {} — run `pnpm build` in www/ first",
            dist_dir.display()
        );
        return;
    }
    let mut entries: Vec<(String, String)> = Vec::new();
    collect_files(&dist_dir, &dist_dir, &mut entries);
    entries.sort();

    // Namespace the generated statics per app (two embeds coexist in one module).
    let prefix = app.to_ascii_uppercase(); // ADMIN_* / VOICE_*
    let mut code = String::from("// AUTO-GENERATED by build.rs — embedded dist (do not edit)\n");
    for (i, (_rel, abs)) in entries.iter().enumerate() {
        let line = format!("pub static {prefix}_FILE_{i}: &[u8] = include_bytes!(\"{abs}\");");
        code.push_str(&line);
        code.push('\n');
    }
    code.push_str(&format!("pub static {prefix}_FILES: &[(&str, &[u8])] = &[\n"));
    for (i, (rel, _)) in entries.iter().enumerate() {
        code.push_str(&format!("    (\"{rel}\", {prefix}_FILE_{i}),\n"));
    }
    code.push_str("];\n");

    let gen_path = out_dir.join(gen_name);
    fs::write(&gen_path, code).expect("write generated embed file");
    println!("cargo:rerun-if-changed={dist_rel}");
}

/// Recursively collect (relative_path, absolute_path) for all files under root.
#[cfg(feature = "admin-dashboard")]
fn collect_files(root: &PathBuf, dir: &PathBuf, out: &mut Vec<(String, String)>) {
    if let Ok(rd) = fs::read_dir(dir) {
        for entry in rd.flatten() {
            let path = entry.path();
            if path.is_dir() {
                collect_files(root, &path, out);
            } else {
                let rel = path
                    .strip_prefix(root)
                    .expect("path under root")
                    .to_string_lossy()
                    .replace('\\', "/");
                out.push((rel, path.to_string_lossy().replace('\\', "/")));
            }
        }
    }
}
