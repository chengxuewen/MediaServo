//! Field session config (contract §4 implementation).
//!
//! `PushConfig`/`PullConfig` are the session entry configs; `PublishOptions` carries the rich publish
//! options (MVP lands only codec + encoder_backend; the rest expand as real transports land).

use mediaservo_common::protocol::PeerRole;
use mediaservo_webrtc::rtp::{RTCDegradationPreference, RTCRtpContentHint};

/// Push strategy tier (qos-framerate-priority, AD-1: the user surface only exposes the strategy axis,
/// primitive expansion is done by the bundle() pure table, and merge arbitration lives in host translate).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StreamMode {
    /// Realtime first: keep fps, reduce resolution + Fluid hint + bitrate floor (recommended for teleop). The floor value is not in this layer —
    /// per-frame bytes at constant size depend on the source fps; host translate consumes the resolved fps (D282).
    Smooth,
    /// libwebrtc balanced dual degradation (default; behavior byte-identical to the status quo)
    Balanced,
    /// Quality first: keep resolution, reduce fps + 3000kbps ceiling (recommended for forensics, AD-3)
    Quality,
}

impl StreamMode {
    /// CLI/config string form (symmetric with FromStr; shared by translate/streamer).
    pub fn to_str(self) -> &'static str {
        match self {
            StreamMode::Smooth => "smooth",
            StreamMode::Balanced => "balanced",
            StreamMode::Quality => "quality",
        }
    }

    /// Tier → primitive bundle (pure data; table-driven, unit-test friendly).
    pub fn bundle(self) -> PresetBundle {
        match self {
            StreamMode::Smooth => PresetBundle {
                degradation: RTCDegradationPreference::MaintainFramerate,
                content_hint: RTCRtpContentHint::Fluid,
                // Floor handed to the host (fps-linked max(50, fps*100/30); field is fps-unaware) — D282
                min_bitrate_kbps: None,
                bitrate_kbps: None,
            },
            StreamMode::Balanced => PresetBundle::default(),
            StreamMode::Quality => PresetBundle {
                degradation: RTCDegradationPreference::MaintainResolution,
                content_hint: RTCRtpContentHint::None,
                min_bitrate_kbps: None,
                bitrate_kbps: Some(3000),
            },
        }
    }
}

impl std::str::FromStr for StreamMode {
    type Err = String;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_lowercase().as_str() {
            "smooth" => Ok(Self::Smooth),
            "balanced" => Ok(Self::Balanced),
            "quality" => Ok(Self::Quality),
            _ => Err(format!("illegal stream_mode value {s:?} (legal: smooth|balanced|quality)")),
        }
    }
}

/// Primitive set after StreamMode expansion (translate consumes: explicit config > bundle).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct PresetBundle {
    pub degradation: RTCDegradationPreference,
    pub content_hint: RTCRtpContentHint,
    pub min_bitrate_kbps: Option<u32>,
    pub bitrate_kbps: Option<u32>,
}

/// Push session config (contract §4).
#[derive(Debug, Clone)]
pub struct PushConfig {
    /// Signaling WS address, e.g. `ws://host:9800/ws`.
    pub url: String,
    /// PSK auth key.
    pub psk: String,
    /// Room ID.
    pub room: String,
    /// Node role (Host/Pusher).
    pub role: PeerRole,
    /// Push video resolution (width).
    pub width: u32,
    /// Push video resolution (height).
    pub height: u32,
    /// Frame rate (matches the libwebrtc encoder config, C17).
    pub framerate: u32,
    /// Encoding bitrate in kbps.
    pub bitrate_kbps: u32,
    /// Weak-network degradation preference (qos-framerate-priority; default Balanced = setters not called, AD-6).
    pub degradation: RTCDegradationPreference,
    /// Content hint (default None = setter not called; the Smooth tier's bundle is Fluid).
    pub content_hint: RTCRtpContentHint,
    /// Bitrate floor in kbps form of bps (None = no floor; the Smooth tier's floor is generated by the host from the source fps).
    pub min_bitrate_kbps: Option<u32>,
    /// Keyframe interval in seconds (GOP cap, default 2).
    pub keyframe_interval: u64,
    /// D2 local gateway mode: Some(src) = connect via the host-agent gateway
    /// (LocalEnvelope wire, no PSK; the vehicle-wide PSK lives at the agent's remote hop);
    /// None = direct to the server (PSK auth).
    pub gateway_src: Option<String>,
    /// peer_id uniquifying suffix (required for the producer-label device-room form): None = bare role name
    /// ("host"; multiple sessions in one room conflict — same class as PIT-65); Some(s) = "host-s".
    /// host-streamer passes stream.id, so a same-stream restart naturally replaces its own old session (correct takeover semantics).
    pub peer_suffix: Option<String>,
}

impl PushConfig {
    /// Convenience constructor (default 1280x720@30fps / 2000kbps / 2s GOP; direct-server mode).
    pub fn new(url: impl Into<String>, psk: impl Into<String>, room: impl Into<String>) -> Self {
        Self {
            url: url.into(),
            psk: psk.into(),
            room: room.into(),
            role: PeerRole::Host,
            width: 1280,
            height: 720,
            framerate: 30,
            bitrate_kbps: 2000,
            degradation: RTCDegradationPreference::Balanced,
            content_hint: RTCRtpContentHint::None,
            min_bitrate_kbps: None,
            keyframe_interval: 2,
            gateway_src: None,
            peer_suffix: None,
        }
    }

    /// Local gateway mode constructor (D2): url is the host-agent local address, no PSK challenge
    /// (trust boundary 127.0.0.1; the vehicle-wide PSK lives at the agent's remote connection).
    pub fn via_gateway(
        url: impl Into<String>,
        src: impl Into<String>,
        room: impl Into<String>,
    ) -> Self {
        Self::new(url, "", room).with_gateway(src)
    }

    /// Enable local gateway mode (chained; for config reuse).
    pub fn with_gateway(mut self, src: impl Into<String>) -> Self {
        self.gateway_src = Some(src.into());
        self
    }

    /// peer_id uniquifying suffix (chained; required for multiple streams in one device room — peer conflict, same class as PIT-65).
    pub fn with_peer_suffix(mut self, suffix: impl Into<String>) -> Self {
        self.peer_suffix = Some(suffix.into());
        self
    }
}

/// Pull session config (contract §4; MVP defines the type only, connect does not wire the consume chain yet).
#[derive(Debug, Clone)]
pub struct PullConfig {
    /// Signaling WS address.
    pub url: String,
    /// PSK auth key.
    pub psk: String,
    /// Room ID.
    pub room: String,
    /// Node role (Remote/Consumer).
    pub role: PeerRole,
    /// Auto-subscribe to all producers in the room.
    pub auto_subscribe: bool,
}

impl Default for PullConfig {
    fn default() -> Self {
        Self {
            url: String::new(),
            psk: String::new(),
            room: String::new(),
            role: PeerRole::Remote,
            auto_subscribe: true,
        }
    }
}

/// Publish options (contract §4; MVP lands only codec + encoder_backend).
#[derive(Debug, Clone)]
pub struct PublishOptions {
    /// Encoding format (VP8/H264/VP9/AV1, aligned with the router).
    pub codec: String,
    /// Encoder backend (auto/software/hardware).
    pub encoder_backend: String,
    /// producer-label T3: stream business label (e.g. "fl") — passed through on Produce and echoed back by NewProducer;
    /// None = legacy host form (consumer falls back to the first track). additive.
    pub label: Option<String>,
}

impl Default for PublishOptions {
    fn default() -> Self {
        Self { codec: "vp8".to_string(), encoder_backend: "auto".to_string(), label: None }
    }
}
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn push_config_defaults_sane() {
        let cfg = PushConfig::new("ws://x", "psk", "room");
        assert_eq!(cfg.width, 1280);
        assert_eq!(cfg.height, 720);
        assert_eq!(cfg.framerate, 30);
        assert_eq!(cfg.bitrate_kbps, 2000);
        assert_eq!(cfg.keyframe_interval, 2);
        assert_eq!(cfg.role, PeerRole::Host);
    }

    #[test]
    fn push_config_custom_values_preserved() {
        let mut cfg = PushConfig::new("ws://x", "psk", "room");
        cfg.width = 640;
        cfg.height = 480;
        cfg.framerate = 15;
        cfg.bitrate_kbps = 800;
        cfg.keyframe_interval = 4;
        assert_eq!(cfg.width, 640);
        assert_eq!(cfg.framerate, 15);
        assert_eq!(cfg.bitrate_kbps, 800);
        assert_eq!(cfg.keyframe_interval, 4);
    }

    #[test]
    fn publish_options_defaults_vp8_auto() {
        let opts = PublishOptions::default();
        assert_eq!(opts.codec, "vp8");
        assert_eq!(opts.encoder_backend, "auto");
    }

    #[test]
    fn pull_config_default_auto_subscribe() {
        let cfg = PullConfig::default();
        assert!(cfg.auto_subscribe);
        assert_eq!(cfg.role, PeerRole::Remote);
    }

    #[test]
    fn push_config_url_trims_trailing_slash_in_connect() {
        // SignalClient internally trim_end_matches('/') — config stays as-is, handled at connect time
        let cfg = PushConfig::new("ws://host:9800/ws/", "psk", "room");
        assert_eq!(cfg.url, "ws://host:9800/ws/");
    }

    #[test]
    fn push_config_gateway_mode_defaults_off_and_switchable() {
        // D2: default direct-to-server (gateway_src=None); via_gateway/with_gateway switches
        let direct = PushConfig::new("ws://x", "psk", "room");
        assert_eq!(direct.gateway_src, None, "default should connect direct to the server");
        let gw = PushConfig::via_gateway("ws://127.0.0.1:17980/ws", "child-1", "room");
        assert_eq!(gw.gateway_src.as_deref(), Some("child-1"));
        assert_eq!(gw.psk, "", "gateway mode has no PSK");
        let chained = direct.clone().with_gateway("child-2");
        assert_eq!(chained.gateway_src.as_deref(), Some("child-2"));
    }

    // qos-framerate-priority T3: StreamMode preset table + PushConfig default equivalence
    #[test]
    fn stream_mode_from_str_legal_and_illegal() {
        assert_eq!("smooth".parse::<StreamMode>().unwrap(), StreamMode::Smooth);
        assert_eq!("balanced".parse::<StreamMode>().unwrap(), StreamMode::Balanced);
        assert_eq!("quality".parse::<StreamMode>().unwrap(), StreamMode::Quality);
        assert!("SMOOTH ".parse::<StreamMode>().is_ok(), "case/whitespace insensitive");
        let e = "turbo".parse::<StreamMode>().unwrap_err();
        assert!(e.contains("smooth|balanced|quality"), "error message contains the legal set: {e}");
        assert!("".parse::<StreamMode>().is_err());
    }

    #[test]
    fn preset_bundle_table_per_ad2_ad3_ad4() {
        use mediaservo_webrtc::rtp::{RTCDegradationPreference, RTCRtpContentHint};
        let s = StreamMode::Smooth.bundle();
        assert_eq!(s.degradation, RTCDegradationPreference::MaintainFramerate);
        assert_eq!(s.content_hint, RTCRtpContentHint::Fluid);
        assert_eq!(s.min_bitrate_kbps, None, "smooth floor handed to the host (fps-linked, D282)");
        assert_eq!(s.bitrate_kbps, None, "smooth leaves the bitrate ceiling untouched");
        let b = StreamMode::Balanced.bundle();
        assert_eq!(b.degradation, RTCDegradationPreference::Balanced);
        assert_eq!(b.content_hint, RTCRtpContentHint::None);
        assert_eq!(b.min_bitrate_kbps, None);
        assert_eq!(b.bitrate_kbps, None);
        let q = StreamMode::Quality.bundle();
        assert_eq!(q.degradation, RTCDegradationPreference::MaintainResolution);
        assert_eq!(q.content_hint, RTCRtpContentHint::None);
        assert_eq!(q.min_bitrate_kbps, None);
        assert_eq!(q.bitrate_kbps, Some(3000));
    }

    #[test]
    fn push_config_new_defaults_match_legacy_behavior() {
        // AD-6: default construction = status-quo behavior (Balanced/None/None → session calls no new setters)
        let cfg = PushConfig::new("ws://x", "psk", "room");
        assert_eq!(cfg.degradation, mediaservo_webrtc::rtp::RTCDegradationPreference::Balanced);
        assert_eq!(cfg.content_hint, mediaservo_webrtc::rtp::RTCRtpContentHint::None);
        assert_eq!(cfg.min_bitrate_kbps, None);
    }
}
