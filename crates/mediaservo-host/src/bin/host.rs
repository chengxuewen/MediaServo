//! host CLI: operational entry point for the business view (Phase A).
//!
//! Subcommands (parsed by hand from `std::env::args`; Phase A avoids clap):
//! - `host init [<dir>]`        — generate `etc/host.yaml` template + `etc/link/signing.pem`
//!   (Ed25519 PKCS#8 keypair, 0600) + `etc/link/ros_bridge.yaml` (B3: single source of truth
//!   for ROS node config — topic list + token paths, derived from the host.yaml camera/stream lists)
//!   + auto-issue the standard vehicle token set (G1: `host token issue --all`, idempotent)
//! - `host start [<dir>]` — read etc/host.yaml → validate → translate → write run/oxfile.toml
//!   → `oxmgr apply run/oxfile.toml` to bring up all host processes
//! - `host apply [<dir>]`  — same as above (E4: local equivalent of the cloud config loop;
//!   incremental: new Start / changed Recreate / unchanged Noop)
//! - `host restart [<dir>]`— `oxmgr stop <oxfile>` then re-apply (full restart)
//! - `host stop [<dir>]`  — `oxmgr stop run/oxfile.toml` + `oxmgr delete run/oxfile.toml`
//!   OxMgr verb check (C11/C18, source: .refinfo/OxMgr/docs/CLI.md + SKILL.md):
//!   `apply <config>` / `list [--json]` / `stop <name|id|config>` / `delete <name|id|config>`
//!   (**no** `stop/delete --namespace` flags; the config target auto-resolves all apps
//!   inside the oxfile, see the "Lifecycle" section of CLI.md).

