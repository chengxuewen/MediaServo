// ── startup-hardening S1: conflict gate v2 — identity check + port comparison (§2.1/§5 pinned form) ────
// host-side standalone implementation (host is a standalone bin; PLAN §3 T4a ruled shared-sinking as a separate project) —
// same semantics as server lifecycle/startup.rs; test fixtures cross-confirm within the family.

/// Unit identity classification (host view): Host = same-class / Server = cross-domain / Unknown = our product's oxmgr prefix but unrecognized
/// (WARN list, never silenced, never a takeover candidate) / Foreign = not oxmgr.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum S1UnitIdentity {
    Host,
    Server,
    Unknown,
    Foreign,
}
use S1UnitIdentity::{
    Foreign as S1Foreign, Host as S1Host, Server as S1Server, Unknown as S1Unknown,
};

/// Known brand set (cross-brand lookup union — startup-stop-followups ruling 1; value-mirrored
/// with server lifecycle/startup.rs KNOWN_BRANDS; the two crate constants are not promoted — plan §3).
const S1_KNOWN_BRANDS: &[&str] = &["mediaservo", "msrtc"];

/// Unit filename → identity (exact prefix match — contains is forbidden; B1).
fn startup_classify_unit(name: &str) -> S1UnitIdentity {
    startup_classify_unit_with(name, &mediaservo_common::brand::media_brand())
}

/// Same as above (brand parameter seam — K1 pinned tests dual-view; production goes through the thin shell).
fn startup_classify_unit_with(
    name: &str,
    brand: &mediaservo_common::brand::Brand,
) -> S1UnitIdentity {
    let stem = name.strip_suffix(".service").unwrap_or(name);
    let Some(rest) = stem.strip_prefix("oxmgr-").or((stem == "oxmgr").then_some("")) else {
        return S1Foreign;
    };
    // server domain (cross-domain peer) checked first = full enumeration of known brands `{bin_prefix}server-` ∪ current brand form
    // (before host — `mediaservo-server-` ⊃ the `mediaservo-` prefix; checking host first would swallow server units).
    let mut server_forms: Vec<String> = S1_KNOWN_BRANDS
        .iter()
        .map(|b| {
            format!("{}server-", mediaservo_common::brand::media_brand_from(Some(b)).bin_prefix)
        })
        .collect();
    server_forms.push(format!("{}server-", brand.bin_prefix));
    server_forms.sort();
    server_forms.dedup();
    if server_forms.iter().any(|f| rest.starts_with(f.as_str())) {
        return S1Server;
    }
    // host domain = known brands two forms (legacy `host-` + each brand `<brand>-`) ∪ current brand two forms.
    let mut host_forms: Vec<String> = S1_KNOWN_BRANDS
        .iter()
        .map(|b| {
            mediaservo_common::brand::media_brand_from(Some(b))
                .unit_prefix
                .trim_start_matches("oxmgr-")
                .to_string()
        })
        .chain([
            brand.unit_prefix.trim_start_matches("oxmgr-").to_string(),
            format!("{}-", brand.id),
        ])
        .collect();
    host_forms.sort();
    host_forms.dedup();
    if host_forms.iter().any(|f| rest.starts_with(f.as_str())) {
        return S1Host;
    }
    S1Unknown
}

/// Unit text → instance dir (dual keys: OXMGR_HOME= first, on miss fall to OXMGR_DATA_DIR= — reap.rs precedent;
/// the value form `<instance>/run/oxmgr`, hop up two levels).
fn startup_unit_instance_dir(unit_text: &str) -> Option<std::path::PathBuf> {
    let envs: Vec<&str> =
        unit_text.lines().filter_map(|l| l.trim().strip_prefix("Environment=")).collect();
    let val = envs
        .iter()
        .find_map(|l| l.strip_prefix("OXMGR_HOME=").map(|v| v.trim().to_string()))
        .or_else(|| {
            envs.iter()
                .find_map(|l| l.strip_prefix("OXMGR_DATA_DIR=").map(|v| v.trim().to_string()))
        })?;
    let p = std::path::PathBuf::from(val);
    Some(
        p.parent().and_then(std::path::Path::parent).map(std::path::Path::to_path_buf).unwrap_or(p),
    )
}

/// host instance port set (M3 domain-split form: host.yaml signaling local_port + oxfile `--port/--listen`
/// text scan. Derived daemon ports stay out — not app ports). Parse failures skip per source.
fn startup_instance_ports(dir: &std::path::Path) -> Vec<u16> {
    let mut ports = Vec::new();
    if let Ok(cfg) = std::fs::read_to_string(dir.join("etc").join("host.yaml"))
        && let Ok(Some(p)) = mediaservo_host::translate::signaling_local_port(&cfg)
    {
        ports.push(p);
    }
    // the host oxfile currently has no weaknet entries (weaknet deploys only with the server cluster) — text scan of `--port N` /
    // `--listen 127.0.0.1:N` future-proofs entry shapes; live instances yield an empty set = zero false positives.
    if let Ok(ox) = std::fs::read_to_string(dir.join("run").join("oxfile.toml")) {
        for line in ox.lines() {
            let t = line.trim();
            for key in ["--port ", "--listen 127.0.0.1:"] {
                if let Some(rest) = t.split(key).nth(1) {
                    let digits: String = rest.chars().take_while(|c| c.is_ascii_digit()).collect();
                    if let Ok(p) = digits.parse::<u16>() {
                        ports.push(p);
                    }
                }
            }
        }
    }
    ports.sort();
    ports.dedup();
    ports
}

/// Read one tty line (trimmed; EOF/empty = "").
