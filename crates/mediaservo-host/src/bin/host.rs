fn print_usage() {
    let b = mediaservo_common::brand::media_brand();
    // default brand product == "mediaservo-host" — replace is a no-op (zero-behavior-change gate)
    // env overview table comes from the common asset (single source of truth; last line notes that manual env lines in the host tree are ineffective).
    println!(
        "{}",
        format!("{}\n\n{}", USAGE, mediaservo_common::env_usage_text())
            .replace("mediaservo-host", b.product)
    );
}

fn eprint_usage() {
    let b = mediaservo_common::brand::media_brand();
    eprintln!("{}", USAGE.replace("mediaservo-host", b.product));
}

fn main() {
    let mut args = std::env::args();
    let _prog = args.next();
    let Some(cmd) = args.next() else {
        print_usage();
        return;
    };
    if cmd == "-h" || cmd == "--help" {
        print_usage();
        return;
    }
    let code = match cmd.as_str() {
        "init" => cmd_init(&mut args),
        "start" => cmd_apply_impl(&mut args, "start"),
        "apply" => cmd_apply_impl(&mut args, "apply"),
        "restart" => cmd_restart(&mut args),
        "stop" => cmd_stop(&mut args),
        "status" => cmd_status(&mut args),
        "doctor" => cmd_doctor(&mut args),
        "token" => cmd_token(&mut args),
        // oxmgr proxy (mode D: unified entry inside the host dir) — oxmgr must be on PATH (install packs it into bin/)
        "startup" => cmd_startup(&mut args),
        "monit" => cmd_oxmgr(&mut args, &["ui"]),
        "ps" => cmd_oxmgr(&mut args, &["list"]),
        "logs" => cmd_oxmgr(&mut args, &["logs"]),
        "version" => {
            println!(
                "{} {}",
                mediaservo_common::brand::media_brand().product,
                env!("CARGO_PKG_VERSION")
            );
            0
        }
        _ => {
            eprintln!("unknown subcommand: {cmd}");
            eprint_usage();
            2
        }
    };
    std::process::exit(code);
}

/// Parse the instance-dir argument of a subcommand (**positional**, default `.host/`).
///
/// Guard: the dir is positional, not a flag — any parameter starting with `--` is rejected outright.
/// (`host init --dir` incident: "--dir" was once treated as a path and created a directory; the
/// root cause was flag/positional inconsistency — with the dir unified as positional, a -- prefix must be a user typo.)
fn parse_dir(args: &mut impl Iterator<Item = String>) -> Result<PathBuf, String> {
    let Some(arg) = args.next() else {
        // smart defaults (install-and-go): (1) cwd holds an instance (etc/host.yaml) → ".";
        // (2) an instance next to the binary (install layout: etc/host.yaml beside bin/) → the binary dir;
        // (3) otherwise .host/ (legacy root-dir instance compat)
        if PathBuf::from("etc/host.yaml").exists() {
            return Ok(PathBuf::from("."));
        }
        // (2) instance next to / above the binary dir (install layout: <inst>/bin/msrtc-host + <inst>/etc/host.yaml)
        //    → locate the install root, so "running from any dir points at this machine's instance"
        if let Some(exe_dir) =
            std::env::current_exe().ok().and_then(|p| p.parent().map(|d| d.to_path_buf()))
        {
            if exe_dir.join("etc").join("host.yaml").exists() {
                return Ok(exe_dir.clone());
            }
            if let Some(inst_root) = exe_dir.parent()
                && inst_root.join("etc").join("host.yaml").exists()
            {
                return Ok(inst_root.to_path_buf());
            }
        }
        return Ok(PathBuf::from(".host"));
    };
    if arg.starts_with("--") {
        return Err(format!(
            "instance dir argument must not start with -- (the dir is positional): {arg}"
        ));
    }
    if args.next().is_some() {
        return Err("the instance dir accepts exactly one positional argument".to_string());
    }
    Ok(PathBuf::from(arg))
}

/// `host init <dir>`: generate the etc/host.yaml template + etc/link/signing.pem (Ed25519, 0600)
/// + etc/link/ros_bridge.yaml (topic list + token paths, derived from host.yaml).
fn cmd_init(args: &mut impl Iterator<Item = String>) -> i32 {
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    let etc = dir.join("etc");
    let link = etc.join("link");
    if let Err(e) = std::fs::create_dir_all(&link) {
        eprintln!("init: failed to create {}: {e}", link.display());
        return 1;
    }

    let cfg_path = etc.join("host.yaml");
    if cfg_path.exists() {
        eprintln!("init: {} already exists, skipping", cfg_path.display());
    } else if let Err(e) = std::fs::write(&cfg_path, HOST_TOML_TEMPLATE) {
        eprintln!("init: failed to write {}: {e}", cfg_path.display());
        return 1;
    } else {
        println!("generated {}", cfg_path.display());
    }

    let pem_path = link.join("signing.pem");
    if pem_path.exists() {
        eprintln!("init: {} already exists, skipping", pem_path.display());
    } else {
        match gen_signing_pem() {
            Ok(pem) => {
                if let Err(e) = write_private_pem(&pem_path, pem.as_bytes()) {
                    eprintln!("init: failed to write {}: {e}", pem_path.display());
                    return 1;
                }
                println!("generated {} (Ed25519 private key, 0600)", pem_path.display());
            }
            Err(e) => {
                eprintln!("init: failed to generate Ed25519 key: {e}");
                return 1;
            }
        }
    }

    // G4+device-enroll: device identity identity.json (D-H13 instance root, 0600; idempotent — generated
    // only when missing; overwriting would invalidate the server-side registration; new shape {device_id}, the public-key fingerprint IS the credential). Corrupt files error explicitly.
    let id_path = dir.join(mediaservo_host::identity::IDENTITY_FILE);
    let id_pre_existing = id_path.exists();
    match mediaservo_host::identity::ensure_identity(&dir) {
        Ok(device_id) => {
            if id_pre_existing {
                eprintln!("init: {} already exists, skipping", id_path.display());
            } else {
                let fp = mediaservo_host::identity::load_device_identity(&dir)
                    .ok()
                    .flatten()
                    .map(|i| format!(", pubkey fingerprint={}", i.pubkey_b64))
                    .unwrap_or_default();
                println!("generated {} (device_id={device_id}{fp}, 0600)", id_path.display());
            }
        }
        Err(e) => {
            eprintln!("init: {e}");
            return 1;
        }
    }

    // generate ros_bridge.yaml (B3): topic list + token paths, single source of truth for ROS node config.
    // parsed from the existing host.yaml (the template init just wrote, or the user edited it); a parse
    // failure errors out — silently writing an empty list would leave the ROS node connected to no topic (C15).
    let cfg_text = match std::fs::read_to_string(&cfg_path) {
        Ok(cfg) => cfg,
        Err(e) => {
            eprintln!("init: failed to read {}: {e}", cfg_path.display());
            return 1;
        }
    };
    let (sources, streams) = match mediaservo_host::translate::camera_and_stream_ids(&cfg_text) {
        Ok(ids) => ids,
        Err(e) => {
            eprintln!("init: {e}");
            return 1;
        }
    };
    let token_path = std::path::absolute(link.join("ros-vision.token"))
        .unwrap_or_else(|_| link.join("ros-vision.token"))
        .to_string_lossy()
        .into_owned();
    let yaml = mediaservo_link::bridge::ros_bridge(&sources, &streams, &token_path);
    let ros_path = link.join("ros_bridge.yaml");
    if let Err(e) = std::fs::write(&ros_path, &yaml) {
        eprintln!("init: failed to write {}: {e}", ros_path.display());
        return 1;
    }
    println!("generated {}", ros_path.display());
    // G1: issue the standard vehicle token set (idempotent — D-H10 fixed tokens, skip existing)
    if issue_all(&dir, DEFAULT_TOKEN_TTL_SECS) != 0 {
        return 1;
    }
    0
}

/// Generate an Ed25519 PKCS#8 PEM private key (consumed by link token signing, D238).
fn gen_signing_pem() -> Result<String, String> {
    use ed25519_dalek::pkcs8::EncodePrivateKey;
    let mut csprng = rand_core::OsRng;
    let signing = ed25519_dalek::SigningKey::generate(&mut csprng);
    let doc = signing.to_pkcs8_pem(pkcs8::LineEnding::LF).map_err(|e| e.to_string())?;
    Ok(doc.to_string())
}

/// Write a credential file (private key / capability token) and set 0600 permissions.
fn write_private_pem(path: &Path, data: &[u8]) -> std::io::Result<()> {
    use std::io::Write;
    let mut f = std::fs::File::create(path)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        f.set_permissions(std::fs::Permissions::from_mode(0o600))?;
    }
    f.write_all(data)
}

/// `host start [<dir>]` / `host apply [<dir>]` (shared implementation): read host.yaml → validate →
/// translate → atomically write run/oxfile.toml → `oxmgr apply` (incremental: new Start / changed
/// Recreate / unchanged Noop). verb = "start"|"apply" (log prefix).
fn cmd_apply_impl(args: &mut impl Iterator<Item = String>, verb: &str) -> i32 {
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    // multi-instance contention detection: the host-agent local gateway port is taken = another host instance is running.
    // interactive either/or (non-interactive defaults to exit): quit / take over (stop the old instance, start this one).
    if verb == "start"
        && let Some(port) = agent_port_in_use(&dir)
    {
        let old_dir = find_other_instance_dir();
        eprintln!(
            "detected another running host instance (local signaling gateway port {port} in use)"
        );
        // start-conflict-doctor T3: identify the occupant (pid/exe/deleted/parent) — identification only, no killing.
        for r in mediaservo_host::conflict::diagnose_port(port) {
            eprintln!("  {}", r.line());
            if r.deleted {
                eprintln!("  → exe deleted (upgrade leftover); kill {} then rerun", r.pid);
            }
        }
        if let Some(od) = &old_dir {
            eprintln!("  old instance dir: {}", od.display());
        } else {
            eprintln!("  (could not locate the old instance dir — port held by another program?)");
        }
        if !std::io::IsTerminal::is_terminal(&std::io::stdin()) {
            eprintln!(
                "  non-interactive environment — exiting (for intentional multi-instance: configure distinct [signaling] local_port + room to coexist)"
            );
            return 1;
        }
        eprint!(
            "  enter y to take over (stop the old instance and start this one) / any other input to quit: "
        );
        let _ = std::io::Write::flush(&mut std::io::stdout());
        let mut ans = String::new();
        let _ = std::io::stdin().read_line(&mut ans);
        if !ans.trim().eq_ignore_ascii_case("y") {
            return 1;
        }
        if let Some(od) = old_dir {
            let oxfile = od.join("run").join("oxfile.toml");
            let ox = oxfile.to_str().unwrap_or_default().to_string();
            eprintln!("takeover: stopping old instance {}", od.display());
            let _ = run_oxmgr_in(Some(&od), &["stop", &ox]);
            let _ = run_oxmgr_in(Some(&od), &["delete", &ox]);
        } else {
            // PIT-155: under a branded deploy the old instance may not be locatable (process name msrtc-agent, not host-agent) —
            // continuing to clear SHM + apply would then clash with the surviving old process (camera EBUSY / SHM link drop → black web page).
            eprintln!(
                "takeover aborted: old instance dir not located — old process may still be running"
            );
            eprintln!(
                "  starting directly would cause resource contention (camera EBUSY / SHM link drop)"
            );
            eprintln!(
                "  stop the old instance manually first (e.g. kill <old pid> or reboot) then retry"
            );
            return 1;
        }
    }
    // C25: clear SHM residue before a full start; apply (hot update) does not (processes running, SHM in use)
    if verb == "start" {
        clear_iceoryx_residue("start");
    }
    match mediaservo_host::translate::apply_config(&dir) {
        Ok(()) => {
            println!("{verb}: applied {}", dir.join("run").join("oxfile.toml").display());
            // log sync: OxMgr 0.5.0 [apps.logs] override not wired (upstream) —
            // logs land in the oxmgr log_dir; symlink host process logs into the instance run/logs/ (D-H13 layout)
            sync_host_logs(&dir);
            0
        }
        Err(e) => {
            eprintln!("{verb}: {e}");
            1
        }
    }
}

/// C25: iceoryx2 SHM residue (SystemInFlux) makes capturer/streamer subscription open fail —
/// must clean after a full stop (start/restart); apply (hot update) does not (processes running, SHM in use).
fn clear_iceoryx_residue(verb: &str) {
    for p in ["/tmp/iceoryx2", "/dev/shm/iox2_*"] {
        let _ = std::process::Command::new("rm").args(["-rf", p]).status();
    }
    println!("{verb}: cleared iceoryx2 SHM residue (C25)");
}

/// `host restart [<dir>]`: `oxmgr stop <oxfile>` (stop all apps) then re-apply (full restart).
fn cmd_restart(args: &mut impl Iterator<Item = String>) -> i32 {
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    let oxfile = dir.join("run").join("oxfile.toml");
    if !oxfile.exists() {
        eprintln!("restart: no {} — run host start/apply first", oxfile.display());
        return 1;
    }
    let code = run_oxmgr_in(Some(&dir), &["stop", oxfile.to_str().expect("oxfile path utf8")]);
    if code != 0 {
        return code;
    }

    // full restart = stop then start: clear SHM residue like start does (a restart skipping cleanup → SystemInFlux black screen)
    clear_iceoryx_residue("restart");
    match mediaservo_host::translate::apply_config(&dir) {
        Ok(()) => {
            println!("restart: fully restarted ({}", dir.join("run").join("oxfile.toml").display());
            0
        }
        Err(e) => {
            eprintln!("restart: {e}");
            1
        }
    }
}

/// `host stop [<dir>]`: `oxmgr stop <oxfile>` + `oxmgr delete <oxfile>` + fallback cleanup of
/// leftover host-namespace apps (from historical renames / interrupted applies) — the namespace must be empty after stop.
///
/// With no run/oxfile.toml (never applied, or already deleted) → still sweep leftovers; succeed directly if none.
fn cmd_stop(args: &mut impl Iterator<Item = String>) -> i32 {
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    let mut failed = 0;
    let oxfile = dir.join("run").join("oxfile.toml");
    if oxfile.exists() {
        let oxfile = oxfile.to_str().expect("oxfile path utf8");
        if run_oxmgr_in(Some(&dir), &["stop", oxfile]) != 0 {
            failed = 1;
        }
        if run_oxmgr_in(Some(&dir), &["delete", oxfile]) != 0 {
            failed = 1;
        }
    } else {
        println!("stop: no {}, no managed processes", oxfile.display());
    }
    // fallback: delete leftover host-namespace apps (left behind outside the oxfile) one by one
    // (same per-instance daemon env — querying the default daemon without env returns empty, making leftover cleanup ineffective)
    let env = mediaservo_host::translate::oxmgr_env(&dir);
    match mediaservo_host::translate::live_host_apps(&env) {
        Ok(leftovers) => {
            for name in leftovers {
                eprintln!("stop: cleaning leftover app {name}");
                if run_oxmgr_in(Some(&dir), &["delete", &name]) != 0 {
                    failed = 1;
                }
            }
        }
        Err(e) => {
            eprintln!("stop: leftover query failed: {e}");
            failed = 1;
        }
    }
    if failed == 0 {
        // start-conflict-doctor T4: stop self-proof (poll ≤5s until the family count reaches zero)
        let mut verified = false;
        for _ in 0..10 {
            let gone = [
                "host-agent",
                "host-streamer",
                "host-capturer",
                "host-recorder",
                "host-controller",
                "host-emergency",
                "host-audio",
            ]
            .iter()
            .all(|app| mediaservo_host::conflict::diagnose_app_gone(app));
            if gone {
                verified = true;
                break;
            }
            std::thread::sleep(std::time::Duration::from_millis(500));
        }
        println!(
            "stop: all host processes stopped{}",
            if verified {
                " — sweep verified ✓"
            } else {
                " — ⚠ sweep could not be verified (see leftovers in ps)"
            }
        );
    }
    failed
}

/// `host status [<dir>]`: `oxmgr list --json` filtered to the host namespace, rendered as a status table.
fn cmd_status(args: &mut impl Iterator<Item = String>) -> i32 {
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    let out = match oxmgr_env(&dir).args(["list", "--json"]).output() {
        Ok(out) => out,
        Err(e) => {
            eprintln!("oxmgr execution failed: {e} — install OxMgr and add it to PATH first");
            return 1;
        }
    };
    if !out.status.success() {
        eprintln!("oxmgr list failed: {}", String::from_utf8_lossy(&out.stderr).trim());
        return 1;
    }
    let procs: serde_json::Value = match serde_json::from_slice(&out.stdout) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("status: failed to parse oxmgr list --json output: {e}");
            return 1;
        }
    };
    let Some(rows) = procs.as_array() else {
        eprintln!("status: oxmgr list --json output is not an array");
        return 1;
    };
    let host_procs: Vec<&serde_json::Value> = rows
        .iter()
        .filter(|p| {
            p.get("namespace").and_then(|n| n.as_str())
                == Some(mediaservo_common::brand::media_brand().namespace)
        })
        .collect();
    if host_procs.is_empty() {
        println!("no managed processes in the host namespace (run host start [<dir>] first)");
        return 0;
    }
    println!("{:<28} {:<10} PID", "NAME", "STATUS");
    for p in &host_procs {
        let name = p.get("name").and_then(|v| v.as_str()).unwrap_or("?");
        let status = p.get("status").and_then(|v| v.as_str()).unwrap_or("?");
        let pid = p.get("pid").and_then(|v| v.as_u64()).map_or("-".to_string(), |v| v.to_string());
        println!("{name:<28} {status:<10} {pid}");
    }
    0
}

/// `host token issue`: sign capability tokens with `etc/link/signing.pem` (generated by host init, PKCS#8 Ed25519)
/// (C4 minimal issuance → G1 full issuance: --all/--for-ros/--ttl/validation/audit).
///
/// A token is written as a single TokenFile (embedded public key + JWT, MSTK format) — the same shape as
/// the `<cam>.token`/`<stream>.token`/`recorder.token`/`agent.token` files referenced by oxfile `--token`
/// in translate.rs. Default TTL is 10 years (D-H10 fixed-token policy).
///
/// Every issuance writes an audit record (etc/link/issuance.jsonl JSONL, D-H10 audit discipline).
const TOKEN_USAGE: &str = "Usage:\n  host token issue --role <capture|processor|pusher|puller|recorder|control|perception|monitor> --node <id> [--topic <T>]... --out <path> [--ttl <secs>] [<dir>]\n  host token issue --all [--ttl <secs>] [<dir>]      # issue the standard vehicle token set from host.yaml (idempotent, skips existing)\n  host token issue --for-ros [--ttl <secs>] [<dir>]  # Perception preset (node=ros-vision, out=etc/link/ros-vision.token, consistent with ros_bridge.yaml)\nROS token example: host token issue --role perception --node ros-vision --out etc/link/ros-vision.token <dir>";
/// D-H10 fixed-token policy: tokens stay valid long-term and are not rotated with deployments.
const DEFAULT_TOKEN_TTL_SECS: u64 = 10 * 365 * 24 * 3600;
/// --for-ros preset: the ROS vision node identity (same file as the ros_bridge.yaml token_path).
const ROS_TOKEN_NODE: &str = "ros-vision";
const ROS_TOKEN_FILE: &str = "ros-vision.token";

fn cmd_token(args: &mut impl Iterator<Item = String>) -> i32 {
    let Some(sub) = args.next() else {
        eprintln!("{TOKEN_USAGE}");
        return 2;
    };
    if sub != "issue" {
        eprintln!("unknown token subcommand: {sub}");
        eprintln!("{TOKEN_USAGE}");
        return 2;
    }
    cmd_token_issue(args)
}

fn cmd_token_issue(args: &mut impl Iterator<Item = String>) -> i32 {
    let mut role: Option<Role> = None;
    let mut node: Option<String> = None;
    let mut topics: Vec<String> = Vec::new();
    let mut out: Option<PathBuf> = None;
    let mut ttl: u64 = DEFAULT_TOKEN_TTL_SECS;
    let mut all = false;
    let mut for_ros = false;
    let mut dir: Option<PathBuf> = None;
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--role" => {
                let Some(v) = args.next() else {
                    eprintln!("--role missing value");
                    return 2;
                };
                match parse_role(&v) {
                    Ok(r) => role = Some(r),
                    Err(e) => {
                        eprintln!("{e}");
                        return 2;
                    }
                }
            }
            "--node" => {
                let Some(v) = args.next() else {
                    eprintln!("--node missing value");
                    return 2;
                };
                if let Err(e) = check_node_id(&v) {
                    eprintln!("{e}");
                    return 2;
                }
                node = Some(v);
            }
            "--topic" => {
                let Some(v) = args.next() else {
                    eprintln!("--topic missing value");
                    return 2;
                };
                if v.is_empty() {
                    eprintln!("--topic must not be empty");
                    return 2;
                }
                topics.push(v);
            }
            "--out" => {
                let Some(v) = args.next() else {
                    eprintln!("--out missing value");
                    return 2;
                };
                out = Some(PathBuf::from(v));
            }
            "--ttl" => {
                let Some(v) = args.next() else {
                    eprintln!("--ttl missing value");
                    return 2;
                };
                match v.parse::<u64>() {
                    Ok(t) if t > 0 => ttl = t,
                    _ => {
                        eprintln!("--ttl must be a positive integer of seconds: {v}");
                        return 2;
                    }
                }
            }
            "--all" => all = true,
            "--for-ros" => for_ros = true,
            _ => {
                if arg.starts_with("--") {
                    eprintln!(
                        "instance dir argument must not start with -- (the dir is positional): {arg}"
                    );
                    eprintln!("{TOKEN_USAGE}");
                    return 2;
                }
                if dir.is_some() {
                    eprintln!("unknown argument: {arg}");
                    eprintln!("{TOKEN_USAGE}");
                    return 2;
                }
                dir = Some(PathBuf::from(arg));
            }
        }
    }
    let dir = dir.unwrap_or_else(|| PathBuf::from(".host"));
    if all && for_ros {
        eprintln!("--all and --for-ros are mutually exclusive");
        return 2;
    }
    if (all || for_ros) && (role.is_some() || node.is_some() || !topics.is_empty() || out.is_some())
    {
        let preset = if all { "--all" } else { "--for-ros" };
        eprintln!(
            "{preset} cannot be combined with --role/--node/--topic/--out (arguments are derived from host.yaml / the preset)"
        );
        return 2;
    }
    if all {
        return issue_all(&dir, ttl);
    }
    if for_ros {
        let out = std::path::absolute(dir.join("etc").join("link").join(ROS_TOKEN_FILE))
            .unwrap_or_else(|_| dir.join("etc").join("link").join(ROS_TOKEN_FILE));
        return match issue_one(
            &dir,
            Role::Perception,
            ROS_TOKEN_NODE.to_string(),
            Vec::new(),
            &out,
            ttl,
        ) {
            Ok(()) => {
                println!(
                    "issued Perception token → {} (node={} ttl={}s)",
                    out.display(),
                    ROS_TOKEN_NODE,
                    ttl
                );
                0
            }
            Err(e) => {
                eprintln!("token: {e}");
                1
            }
        };
    }
    let (Some(role), Some(node), Some(out)) = (role, node, out) else {
        eprintln!("missing required arguments: --role/--node/--out");
        eprintln!("{TOKEN_USAGE}");
        return 2;
    };
    // G1 hardening: an explicit --topic must fall inside the role's ACL matrix allowed direction/pattern (over-privilege rejected).
    if let Err(e) = validate_topics(role, &topics) {
        eprintln!("{e}");
        return 2;
    }
    match issue_one(&dir, role, node.clone(), topics, &out, ttl) {
        Ok(()) => {
            println!("issued {:?} token → {} (node={} ttl={}s)", role, out.display(), node, ttl);
            0
        }
        Err(e) => {
            eprintln!("token: {e}");
            1
        }
    }
}

/// G1 hardening: an explicit --topic must match the allowed pattern of the role's ACL matrix direction.
/// Single-direction roles (capture / pusher-recorder-subscribe / monitor) may narrow explicitly;
/// bi-directional or directionless roles (processor/perception/control/puller) reject an explicit
/// --topic — the matrix default is their only grant surface.
fn validate_topics(role: Role, topics: &[String]) -> Result<(), String> {
    if topics.is_empty() {
        return Ok(()); // no explicit topic → matrix default, nothing to validate
    }
    let base = NodeAcl::for_role(NodeId::new(""), role);
    // --topic matched against the subscribe direction (pusher/recorder/monitor/processor)
    if !base.subscribe_allow.is_empty() {
        let allowed = &base.subscribe_allow;
        for t in topics {
            if !allowed.iter().any(|p| FrameTopic::new(t).matches(p)) {
                return Err(format!(
                    "topic {t:?} outside role {:?} subscribe allow patterns: {:?}",
                    role, allowed
                ));
            }
        }
        return Ok(());
    }
    // --topic matched against the publish direction (capture)
    if !base.publish_allow.is_empty() {
        let allowed = &base.publish_allow;
        for t in topics {
            if !allowed.iter().any(|p| FrameTopic::new(t).matches(p)) {
                return Err(format!(
                    "topic {t:?} outside role {:?} publish allow patterns: {:?}",
                    role, allowed
                ));
            }
        }
        return Ok(());
    }
    Err(format!(
        "role {:?} has no direction — explicit --topic only supported for single-direction roles (capture/pusher/recorder); omit --topic for matrix defaults",
        role,
    ))
}

/// G1 hardening: node id charset guard (same rule as host.yaml ids, [A-Za-z0-9_-]+,
/// to prevent malformed claims / path traversal).
fn check_node_id(id: &str) -> Result<(), String> {
    if id.is_empty() || !id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_') {
        return Err(format!("--node invalid: {id:?} (only [A-Za-z0-9_-]+ allowed)"));
    }
    Ok(())
}

/// Single-issuance pipeline: read signing.pem → build_acl → sign → audit → write TokenFile (0600).
/// Audit first: an issuance without an audit record is refused disk write (D-H10 audit discipline — no token exists outside the audit).
fn issue_one(
    dir: &Path,
    role: Role,
    node: String,
    topics: Vec<String>,
    out: &Path,
    ttl: u64,
) -> Result<(), String> {
    let pem_path = dir.join("etc").join("link").join("signing.pem");
    let pem = std::fs::read(&pem_path).map_err(|e| {
        format!("failed to read {}: {e} — run host init <dir> first", pem_path.display())
    })?;
    let signing = ed25519_dalek::SigningKey::from_pkcs8_pem(&String::from_utf8_lossy(&pem))
        .map_err(|e| {
            format!("{} is not a valid PKCS#8 Ed25519 private key: {e}", pem_path.display())
        })?;
    let acl = build_acl(NodeId::new(node.clone()), role, topics.clone())?;
    let sk = Ed25519SigningKey::from_pem(&pem);
    let token =
        CapabilityToken::sign(&acl, ttl, &sk).map_err(|e| format!("signing failed: {e}"))?;
    // TokenFile embeds the verifying-key PEM (derived from the private key, same keypair)
    let vk_pem = signing
        .verifying_key()
        .to_public_key_pem(LineEnding::LF)
        .map_err(|e| format!("failed to export public key: {e}"))?;
    let vk = Ed25519VerifyingKey::from_pem(vk_pem.as_bytes());
    let bytes = TokenFile::encode(&token, &vk);
    append_audit(dir, &role, &node, &topics, out, ttl)?;
    write_private_pem(out, &bytes)
        .map_err(|e| format!("failed to write {}: {e}", out.display()))?;
    Ok(())
}

/// Issuance audit (D-H10): append JSONL to etc/link/issuance.jsonl;
/// each entry has ts/role/node/topics/out/ttl. The file is always 0600 (the issuance credential ledger).
fn append_audit(
    dir: &Path,
    role: &Role,
    node: &str,
    topics: &[String],
    out: &Path,
    ttl: u64,
) -> Result<(), String> {
    use std::io::Write;
    let log = dir.join("etc").join("link").join("issuance.jsonl");
    let entry = serde_json::json!({
        "ts": std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_secs())
            .unwrap_or(0),
        "role": role_name(role),
        "node": node,
        "topics": topics,
        "out": out.to_string_lossy(),
        "ttl": ttl,
    });
    let mut f = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&log)
        .map_err(|e| format!("failed to open {}: {e}", log.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        f.set_permissions(std::fs::Permissions::from_mode(0o600))
            .map_err(|e| format!("failed to set audit {} permissions: {e}", log.display()))?;
    }
    writeln!(f, "{entry}").map_err(|e| format!("failed to write {}: {e}", log.display()))
}

fn role_name(r: &Role) -> &'static str {
    match r {
        Role::Capture => "capture",
        Role::Processor => "processor",
        Role::Pusher => "pusher",
        Role::Puller => "puller",
        Role::Recorder => "recorder",
        Role::Control => "control",
        Role::Perception => "perception",
        Role::Monitor => "monitor",
        _ => "unknown",
    }
}

/// G1: `host token issue --all` — issue the standard vehicle token set from host.yaml (idempotent,
/// skip existing — D-H10 fixed tokens):
///   etc/link/<cam>.token     Capture  publish camera/<cam> (host-capturer-<cam>)
///   etc/link/<stream>.token  Pusher   subscribe camera/<cam> + vision/<cam> + publish stats/*
///   etc/link/recorder.token  Recorder matrix default (subscribe camera/video/vision + publish stats)
///   etc/link/agent.token     Monitor matrix default (subscribe camera/* + stats/* — E2 data-flow monitoring)
/// The ROS token (--for-ros) is not auto-issued — ROS presence is optional.
fn issue_all(dir: &Path, ttl: u64) -> i32 {
    let cfg_path = dir.join("etc").join("host.yaml");
    let cfg = match std::fs::read_to_string(&cfg_path) {
        Ok(c) => c,
        Err(e) => {
            eprintln!(
                "token: failed to read {}: {e} — run host init <dir> first",
                cfg_path.display()
            );
            return 1;
        }
    };
    let sources = match mediaservo_host::translate::camera_configs(&cfg) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("token: {e}");
            return 1;
        }
    };
    let streams = match mediaservo_host::translate::stream_configs(&cfg) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("token: {e}");
            return 1;
        }
    };
    let link = dir.join("etc").join("link");
    let mut issued = 0usize;
    let mut first_err: Option<String> = None;
    'issue: {
        for src in &sources {
            let out = link.join(format!("{}.token", src.id));
            if out.exists() {
                continue;
            }
            match issue_one(
                dir,
                Role::Capture,
                format!("host-capturer-{}", src.id),
                vec![format!("camera/{}", src.id)],
                &out,
                ttl,
            ) {
                Ok(()) => issued += 1,
                Err(e) => {
                    first_err = Some(format!("failed to issue {}: {e}", out.display()));
                    break 'issue;
                }
            }
        }
        for s in &streams {
            // <stream>-stream.token (Pusher) is separate from the sources' <id>.token (Capture) —
            // sharing a name would let Capture occupy the slot via the idempotent skip, and the streamer subscription gets ACL-denied (PIT-139)
            let out = link.join(format!("{}-stream.token", s.id));
            if out.exists() {
                continue;
            }
            let src = s.source.clone();
            match issue_one(
                dir,
                Role::Pusher,
                format!("host-streamer-{}", s.id),
                vec![format!("camera/{src}"), format!("vision/{src}")],
                &out,
                ttl,
            ) {
                Ok(()) => issued += 1,
                Err(e) => {
                    first_err = Some(format!("failed to issue {}: {e}", out.display()));
                    break 'issue;
                }
            }
        }
        let rec = link.join("recorder.token");
        if !rec.exists() {
            match issue_one(dir, Role::Recorder, "host-recorder".to_string(), Vec::new(), &rec, ttl)
            {
                Ok(()) => issued += 1,
                Err(e) => first_err = Some(format!("failed to issue {}: {e}", rec.display())),
            }
        }
        if first_err.is_none() {
            let agent = link.join("agent.token");
            if !agent.exists() {
                match issue_one(
                    dir,
                    Role::Monitor,
                    "host-agent".to_string(),
                    Vec::new(),
                    &agent,
                    ttl,
                ) {
                    Ok(()) => issued += 1,
                    Err(e) => first_err = Some(format!("failed to issue {}: {e}", agent.display())),
                }
            }
        }
    }
    match first_err {
        Some(e) => {
            eprintln!("token: {e}");
            1
        }
        None => {
            println!("issued {issued} link tokens ({})", link.display());
            0
        }
    }
}

fn parse_role(s: &str) -> Result<Role, String> {
    match s.to_ascii_lowercase().as_str() {
        "capture" => Ok(Role::Capture),
        "processor" => Ok(Role::Processor),
        "pusher" => Ok(Role::Pusher),
        "puller" => Ok(Role::Puller),
        "recorder" => Ok(Role::Recorder),
        "control" => Ok(Role::Control),
        "perception" => Ok(Role::Perception),
        "monitor" => Ok(Role::Monitor),
        _ => Err(format!(
            "unknown role: {s} (choices: capture/processor/pusher/puller/recorder/control/perception/monitor)"
        )),
    }
}

/// --topic default = the ACL matrix default (NodeAcl::for_role); an explicit --topic overrides the role's
/// **single-direction** ACL list (publish-type role → publish_allow, subscribe-type role → subscribe_allow).
/// Bi-directional or directionless roles (processor/perception/control/puller) error on an explicit --topic —
/// the C-phase minimal issuance serves single-direction roles only; bi-directional is left to G1 full issuance.
fn build_acl(node_id: NodeId, role: Role, topics: Vec<String>) -> Result<NodeAcl, String> {
    if topics.is_empty() {
        return Ok(NodeAcl::for_role(node_id, role));
    }
    let base = NodeAcl::for_role(node_id, role);
    // --topic controls subscribe direction for subscribe-oriented roles
    if !base.subscribe_allow.is_empty() {
        return Ok(NodeAcl { subscribe_allow: topics, ..base });
    }
    // --topic controls publish direction for publish-oriented roles (Capture)
    if !base.publish_allow.is_empty() {
        return Ok(NodeAcl { publish_allow: topics, ..base });
    }
    Err(format!(
        "role {:?} has no direction — explicit --topic only supported for single-direction roles (capture/pusher/recorder); omit --topic for matrix defaults",
        role,
    ))
}

/// `host doctor [<dir>]`: environment diagnostics. Three checks:
/// (1) oxmgr executable (on PATH) (2) etc/host.yaml parseable (3) host.yaml → oxfile generatable.
/// Exit code = number of failed checks (0..=3).
fn cmd_doctor(args: &mut impl Iterator<Item = String>) -> i32 {
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    let mut failed = 0;

    match Command::new(oxmgr_path()).arg("--version").output() {
        Ok(_) => println!("[ok] oxmgr available"),
        Err(e) => {
            println!(
                "[fail] oxmgr unavailable: {e} — install it and add to PATH first (npm install -g oxmgr)"
            );
            failed += 1;
        }
    }

    let cfg_path = dir.join("etc").join("host.yaml");
    let cfg = match std::fs::read_to_string(&cfg_path) {
        Ok(cfg) => cfg,
        Err(e) => {
            println!(
                "[fail] failed to read {}: {e} — run host init <dir> first",
                cfg_path.display()
            );
            println!(
                "[fail] oxfile generation failed: no config to translate (host.yaml unreadable)"
            );
            return failed + 2; // both (2) and (3) fail due to missing config; one [fail] each to keep the count aligned
        }
    };
    // (2) config parsing shares its source with each consuming process (translate::validate — serde_yaml + field-semantics validation)
    match mediaservo_host::translate::validate(&cfg) {
        Ok(_) => println!("[ok] host.yaml parseable"),
        Err(e) => {
            println!("[fail] host.yaml parse failed: {e}");
            failed += 1;
        }
    }
    match mediaservo_host::translate::to_oxfile(&cfg) {
        Ok(_) => println!("[ok] oxfile generated successfully"),
        Err(e) => {
            println!("[fail] oxfile generation failed: {e}");
            failed += 1;
        }
    }
    if failed == 0 {
        println!("doctor: all checks passed ({})", cfg_path.display());
    }
    failed
}

/// K3 audit of oxmgr subprocess call sites (startup-stop-followups — full surface of the IPC-spawn root fix):
/// ┌ call site ────────────────────────┬ dir source ─────────────────┬ default-form risk ┐
/// │ run_oxmgr_in ×9 (stop/delete/apply) │ all Some(&dir) passed explicitly │ none       │
/// │ oxmgr_env ← run_oxmgr_in/cmd_status/cmd_oxmgr │ caller's dir        │ see next two rows │
/// │ cmd_status (oxmgr list --json)      │ parse_dir smart default    │ low: cwd/exe anchored, may still land on .host │
/// │ cmd_oxmgr (monit/ps/logs passthrough) │ ★ explicit-required after K3 │ old: default "." ← spawn surface now sealed │
/// │ cmd_doctor --version               │ no daemon (pure executability query)│ safe      │
/// │ oxmgr_bin() service install/uninstall/status │ system service ops (no instance-daemon semantics)│ out of scope │
/// └────────────────────────────────────┴──────────────────────────┴───────────┘
/// translate.rs mirrors the chain: oxmgr_apply/live_host_apps/delete all pass oxmgr_env(&dir) explicitly (no default form).
/// Proxy the oxmgr CLI; when oxmgr is not on PATH, print a clear error with install guidance.
/// Inject the instantiated oxmgr environment — multi-instance daemon full isolation:
/// (1) OXMGR_HOME = <dir>/run/oxmgr (data/logs/state) (2) OXMGR_DAEMON_ADDR port derived stably from dir
/// (daemon mutex = TCP port — without isolation the global daemon blocks the instance daemon from starting) (3) OXMGR_DATA_DIR set as well
/// (the name C32 memory uses — same shape as the server oxmgr_cmd; the reap/startup reverse lookup hits on either key).
fn oxmgr_env(dir: &std::path::Path) -> std::process::Command {
    let mut cmd = std::process::Command::new(oxmgr_path());
    // absolutize (a relative OXMGR_HOME depends on the daemon cwd — restarts/system services would misalign)
    let home = dir.canonicalize().unwrap_or_else(|_| dir.to_path_buf()).join("run").join("oxmgr");
    cmd.env("OXMGR_HOME", &home).env("OXMGR_DATA_DIR", &home); // the name C32 memory uses — set both for compat (server oxmgr_cmd same shape)
    let port = instance_daemon_port(&home);
    cmd.env("OXMGR_DAEMON_ADDR", format!("127.0.0.1:{port}"));
    // third mutex point: the webhook API port (by default derived from the global daemon port — without isolation it collides with global 53081)
    cmd.env("OXMGR_API_ADDR", format!("127.0.0.1:{}", port + 1000));
    let _ = &home; // keep the home alive (used by later env entries)
    cmd
}

/// instance daemon port: 18000 + sum of the dir path bytes % 400 (stable — consistent across processes)
fn instance_daemon_port(dir: &std::path::Path) -> u16 {
    let sum: u32 = dir.to_string_lossy().bytes().map(u32::from).sum();
    18000u16 + (sum % 400) as u16
}

fn run_oxmgr_in(dir: Option<&std::path::Path>, args: &[&str]) -> i32 {
    let mut cmd = match dir {
        Some(d) => oxmgr_env(d),
        // K3 spawn gate (all 9 call sites repo-wide now pass Some — zero behavior change, pure defense):
        // a bare Command without instance env → oxmgr CLI IPC silently spawns the default-location daemon based on cwd.
        // The Option signature is kept — a future caller hitting the gate gets a clear error instead of one spawning event.
        None => {
            eprintln!(
                "run_oxmgr_in: None dir is disabled (prevents IPC spawning of the default daemon)"
            );
            return 2;
        }
    };
    match cmd.args(args).status() {
        Ok(status) => status.code().unwrap_or(1),
        Err(e) => {
            eprintln!(
                "oxmgr execution failed: {e} — install OxMgr and add it to PATH first (npm install -g oxmgr, see https://github.com/Vladimir-Urik/OxMgr#install)"
            );
            1
        }
    }
}

/// Pull the instance dir out of the proxy tail args: the last pathlike positional
/// (`.`, `..`, anything containing `/`, or an existing directory) is the dir; the rest
/// pass through to oxmgr untouched (proc name, `--lines`, `-f`...). A trailing bare
/// positional like `logs cam0` is a proc, not a dir — no dir was given, smart default decides.
/// ponytail: a proc name that also names a real directory under cwd would read as dir —
/// dir-last with `/` covers real usage; add a `--dir` flag form only if it ever bites.
fn split_dir_arg(tail: &[String]) -> (Option<PathBuf>, Vec<String>) {
    let is_dir_arg = |a: &str| {
        !a.starts_with('-')
            && (a == "." || a == ".." || a.contains('/') || std::path::Path::new(a).is_dir())
    };
    match tail.iter().rposition(|a| is_dir_arg(a)) {
        Some(i) => {
            let mut rest = tail.to_vec();
            let dir = rest.remove(i);
            (Some(PathBuf::from(dir)), rest)
        }
        None => (None, tail.to_vec()),
    }
}

/// Strict smart default for the proxy commands (parse_dir minus the legacy `.host` guess):
/// (1) cwd carries an etc/host.yaml instance → cwd; (2) an instance beside the binary
/// (exe dir or its parent, the install layout) → that root; otherwise None — the caller
/// must then demand an explicit dir. Rationale (PIT-224): these commands talk to a daemon
/// addressed by dir, and a dir we cannot prove is an instance may spawn one that belongs
/// to nowhere, so the unprovable fallback is sealed.
fn proxy_smart_dir(cwd: &Path, exe_dir: Option<&Path>) -> Option<PathBuf> {
    let has_instance = |d: &Path| d.join("etc").join("host.yaml").exists();
    if has_instance(cwd) {
        return Some(cwd.to_path_buf());
    }
    let exe = exe_dir?;
    if has_instance(exe) {
        return Some(exe.to_path_buf());
    }
    exe.parent().filter(|p| has_instance(p)).map(PathBuf::from)
}

/// Resolve (dir, oxmgr passthrough args) for cmd_oxmgr from the collected tail args.
fn resolve_proxy_dir(tail: &[String]) -> Result<(PathBuf, Vec<String>), &'static str> {
    let (dir, rest) = split_dir_arg(tail);
    if let Some(d) = dir {
        return Ok((d, rest));
    }
    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let exe = std::env::current_exe().ok().and_then(|p| p.parent().map(|d| d.to_path_buf()));
    proxy_smart_dir(&cwd, exe.as_deref())
        .map(|d| (d, rest))
        .ok_or("no instance found in the current dir or beside this binary — pass the instance dir explicitly (e.g. out/host)")
}

/// Proxy oxmgr commands (TUI / list / logs — thin wrapper, stdio inherited).
/// Usage: mediaservo-host <monit|ps|logs [proc] [dir]> — dir optional (strict smart
/// default: cwd instance / instance beside the binary); clear error when oxmgr is not on PATH.
fn cmd_oxmgr(args: &mut impl Iterator<Item = String>, fixed: &[&str]) -> i32 {
    // K3 v2 (this fix): the first K3 shape collected tail args only for logs — monit/ps kept an
    // always-empty parts, so the explicit-dir gate was a dead bolt (the commands were unusable
    // even when passing a dir as the message itself instructed) — and it passed `fixed` to oxmgr
    // twice (`ui ui`). All three forms now collect the tail and resolve dir in resolve_proxy_dir.
    let tail: Vec<String> = args.collect();
    let (dir, passthrough) = match resolve_proxy_dir(&tail) {
        Ok(v) => v,
        Err(e) => {
            eprintln!("{}: {e}", fixed[0]);
            return 2;
        }
    };
    let mut cmd = oxmgr_env(&dir);
    cmd.args(fixed).args(&passthrough);
    match cmd.status() {
        Ok(st) => st.code().unwrap_or(1),
        Err(e) => {
            eprintln!("cannot execute oxmgr: {e}");
            eprintln!(
                "hint: oxmgr ships under the install's bin/ — export PATH=<prefix>/bin:$PATH before use (or use an absolute path)"
            );
            1
        }
    }
}

/// Symlink this instance's process logs from the oxmgr log dir into <dir>/run/logs/ (D-H13 layout).
/// Matches the brand prefix (default host-*, branded msrtc-*) — fixes the D252 branding omission.
/// note: OxMgr 0.5.0 [apps.logs] is wired (measured: writes straight into the instance run/logs); this
/// function is the oxmgr log_dir fallback path (e.g. older daemons that ignore the override).
fn sync_host_logs(dir: &std::path::Path) {
    let log_dir = dirs_log_dir();
    let run_logs = dir.join("run").join("logs");
    let _ = std::fs::create_dir_all(&run_logs);
    let Ok(entries) = std::fs::read_dir(&log_dir) else {
        return;
    };
    let prefix = mediaservo_common::brand::media_brand().app_prefix;
    let mut n = 0;
    for e in entries.flatten() {
        let name = e.file_name();
        let Some(name) = name.to_str() else { continue };
        if !name.starts_with(prefix) {
            continue;
        }
        let link = run_logs.join(name);
        // already exists and points at the same file → skip; otherwise rebuild (update after rotation/rename)
        if let Ok(md) = std::fs::symlink_metadata(&link) {
            if md.file_type().is_symlink()
                && std::fs::read_link(&link).map(|p| p == e.path()).unwrap_or(false)
            {
                continue;
            }
            let _ = std::fs::remove_file(&link);
        }
        if std::os::unix::fs::symlink(e.path(), &link).is_ok() {
            n += 1;
        }
    }
    if n > 0 {
        println!("log sync: {n} process logs → {}", run_logs.display());
    }
}

/// oxmgr log directory (default ~/.local/share/oxmgr/logs; when OXMGR_DATA_DIR is customized, follow the env)
fn dirs_log_dir() -> std::path::PathBuf {
    if let Ok(d) = std::env::var("OXMGR_DATA_DIR") {
        return std::path::PathBuf::from(d).join("logs");
    }
    std::env::var("HOME")
        .map(|h| std::path::PathBuf::from(h).join(".local/share/oxmgr/logs"))
        .unwrap_or_else(|_| std::path::PathBuf::from(".oxmgr/logs"))
}

/// Boot autostart (Linux = systemd user unit; macOS/Windows = via the oxmgr service, not built-in verified).
/// `startup on` = oxmgr startup (register with the system) + service install; `off` = service uninstall.
/// Injecting OXMGR_DATA_DIR keeps daemon state inside the instance (same env as host start; consistency after the service self-starts).
/// First token of ExecStart= in the unit text (the status bin liveness criterion) — mirrored by the same name in server startup.rs.
fn startup_first_token(unit_text: &str) -> Option<String> {
    unit_text
        .lines()
        .find_map(|l| l.trim().strip_prefix("ExecStart="))
        .and_then(|v| v.split_whitespace().next().map(String::from))
}

/// Four-line health view of a single unit (pure render) — mirrors server `status_line` semantics (S2 four-shape pinned tests).
fn startup_status_line(
    unit: &str,
    enabled: Option<&str>,
    active: Option<&str>,
    linger: bool,
    bin_alive: bool,
) -> Vec<String> {
    let mut out = vec![unit.to_string()];
    out.push(format!("  enabled: {}", enabled.unwrap_or("no")));
    let mut daemon_line = format!("  daemon:  {}", active.unwrap_or("inactive"));
    if active == Some("failed") {
        daemon_line.push_str("  ⚠ diagnostics: journalctl --user -u <unit> -n 20");
    }
    out.push(daemon_line);
    let mut linger_line = format!("  linger:  {}", if linger { "enabled" } else { "disabled" });
    if !linger {
        linger_line.push_str(" — will not auto-start after reboot: run loginctl enable-linger");
    }
    out.push(linger_line);
    out.push(if bin_alive {
        "  instance: bin ✓".to_string()
    } else {
        "  ⚠ bin deleted — boot would certainly fail. Sweep: startup off <dir> or systemctl --user disable --now + rm"
            .to_string()
    });
    out
}

/// Unit health verdict (exit semantics): daemon failed / bin missing / enabled is not enabled = unhealthy.
fn startup_unit_healthy(enabled: Option<&str>, active: Option<&str>, bin_alive: bool) -> bool {
    enabled == Some("enabled") && active == Some("active") && bin_alive
}

/// systemctl --user is-enabled (thin exec; failure/empty output → None).
fn startup_systemctl_enabled(unit: &str) -> Option<String> {
    let o = std::process::Command::new("systemctl")
        .args(["--user", "is-enabled", unit])
        .output()
        .ok()?;
    let s = String::from_utf8_lossy(&o.stdout).trim().to_string();
    (!s.is_empty()).then_some(s)
}

/// S3 post-install probe sample (normalized is-active).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum S3ProbeSample {
    Active,
    Failed,
    Other,
}

/// S3 probe verdict: FailFast = failed seen during polling; Ok = sustain recheck passed;
/// FailLate = fell off after first active (late bind failure); Timeout = no active within 5s.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum S3ProbeVerdict {
    Ok,
    FailFast,
    FailLate,
    Timeout,
}

/// S3 post-install probe verdict (pure function, §2.3+m1): Failed fails fast immediately; after the
/// first Active wait for the sustain recheck sample: still Active = Ok, otherwise FailLate; samples
/// exhausted without ever seeing active = Timeout. Samples during the recheck are still is-active, so [Active,Failed] maps to FailLate. Mirrors server lifecycle.
fn s3_probe_verdict(samples: &[S3ProbeSample]) -> S3ProbeVerdict {
    let mut seen_active = false;
    for &smp in samples {
        match smp {
            S3ProbeSample::Failed if !seen_active => return S3ProbeVerdict::FailFast,
            S3ProbeSample::Failed => return S3ProbeVerdict::FailLate,
            S3ProbeSample::Active if !seen_active => seen_active = true,
            S3ProbeSample::Active => return S3ProbeVerdict::Ok,
            S3ProbeSample::Other => {}
        }
    }
    if seen_active { S3ProbeVerdict::FailLate } else { S3ProbeVerdict::Timeout }
}

/// journalctl diagnostic hint line (command-surface pinned test point).
fn s3_probe_failure_hint(unit: &str) -> String {
    format!("journalctl --user -u {unit} -n 20")
}

/// Poll ≤5s (10×500ms) + 2s sustain recheck. I/O runner: sample + sleep; all verdict logic lives in the pure function.
fn s3_probe_startup(unit: &str) -> bool {
    let mut samples: Vec<S3ProbeSample> = Vec::new();
    let mut seen_active = false;
    for _ in 0..10 {
        let smp = match startup_systemctl_active(unit).as_deref() {
            Some("active") => S3ProbeSample::Active,
            Some("failed") => S3ProbeSample::Failed,
            _ => S3ProbeSample::Other,
        };
        let hit = smp == S3ProbeSample::Active;
        samples.push(smp);
        if seen_active {
            break; // the sustain recheck sample is enqueued — one more sample decides (§2.3 "one more is-active")
        }
        if hit {
            seen_active = true;
            std::thread::sleep(std::time::Duration::from_secs(2));
            continue;
        }
        std::thread::sleep(std::time::Duration::from_millis(500));
    }
    match s3_probe_verdict(&samples) {
        S3ProbeVerdict::Ok => true,
        v => {
            let hint = s3_probe_failure_hint(unit);
            match v {
                S3ProbeVerdict::FailFast => {
                    eprintln!("startup on: daemon failed right after start — check: {hint}");
                    eprintln!("  likely cause: port conflict? run doctor / check port usage");
                }
                S3ProbeVerdict::FailLate => {
                    eprintln!(
                        "warning: daemon exited after starting (possible late bind failure) — check: {hint}"
                    );
                }
                _ => {
                    eprintln!("startup on: daemon did not reach active within 5s — check: {hint}");
                    eprintln!("  likely cause: port conflict? run doctor / check port usage");
                }
            }
            false
        }
    }
}

/// systemctl --user is-active (thin exec).
fn startup_systemctl_active(unit: &str) -> Option<String> {
    let o = std::process::Command::new("systemctl")
        .args(["--user", "is-active", unit])
        .output()
        .ok()?;
    let s = String::from_utf8_lossy(&o.stdout).trim().to_string();
    (!s.is_empty()).then_some(s)
}

/// linger state (§5 M2 pinned form `loginctl show-user $(id -u) -p Linger`, no -U; on failure fall back
/// to the existence of `/var/lib/systemd/linger/$USER`) — mirrors server linger_enabled semantics.
fn startup_linger_enabled() -> bool {
    let uid = std::process::Command::new("id")
        .arg("-u")
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty());
    if let Some(uid) = uid
        && let Ok(o) = std::process::Command::new("loginctl")
            .args(["show-user", &uid, "-p", "Linger"])
            .output()
    {
        let s = String::from_utf8_lossy(&o.stdout).trim().to_string();
        if s.contains("Linger=") {
            return s.ends_with("=yes");
        }
    }
    std::env::var("USER")
        .ok()
        .is_some_and(|u| std::path::Path::new("/var/lib/systemd/linger").join(u).exists())
}

/// host-domain unit → bin liveness snapshot (thin IO shell).
struct S2UnitHealth {
    name: String,
    enabled: Option<String>,
    active: Option<String>,
    bin_alive: bool,
}

/// Scan all host-domain units (S1 classifier — the Host domain collects both legacy and brand forms).
fn startup_scan_health() -> (Vec<S2UnitHealth>, Vec<String>) {
    let units_dir = std::path::Path::new(&std::env::var("HOME").unwrap_or_default())
        .join(".config/systemd/user");
    let mut out = Vec::new();
    let mut unknown = Vec::new();
    let Ok(entries) = std::fs::read_dir(&units_dir) else {
        return (out, unknown);
    };
    for e in entries.flatten() {
        let name = e.file_name();
        let Some(name) = name.to_str() else { continue };
        if !name.ends_with(".service") {
            continue;
        }
        match startup_classify_unit(name) {
            S1Foreign => continue,
            S1Unknown => unknown.push(name.to_string()),
            _ => out.push(S2UnitHealth {
                name: name.to_string(),
                enabled: startup_systemctl_enabled(name),
                active: startup_systemctl_active(name),
                bin_alive: std::fs::read_to_string(e.path())
                    .ok()
                    .and_then(|c| startup_first_token(&c))
                    .is_none_or(|p| std::path::Path::new(&p).exists()),
            }),
        }
    }
    out.sort_by(|a, b| a.name.cmp(&b.name));
    (out, unknown)
}

/// off no-arg selection (pure) — mirrors server select_off.
fn startup_select_off(count: usize, tty: bool) -> S2OffSelect {
    match count {
        0 => S2OffSelect::NoneInstalled,
        1 => S2OffSelect::Single,
        _ if tty => S2OffSelect::Prompt,
        _ => S2OffSelect::RejectList,
    }
}

#[derive(Debug, PartialEq, Eq)]
enum S2OffSelect {
    NoneInstalled,
    Single,
    Prompt,
    RejectList,
}

fn cmd_startup(args: &mut impl Iterator<Item = String>) -> i32 {
    let sub = args.next().unwrap_or_default();
    if !matches!(sub.as_str(), "on" | "off" | "status") {
        eprintln!(
            "Usage: mediaservo-host startup <on|off|status> [<dir>] (status/off with no arg = full inventory of this machine)"
        );
        return 2;
    }
    // S2: status/off with no arg = full-inventory default semantics; with <dir> = the existing filtered/targeted-uninstall form.
    if (sub == "status" || sub == "off") && args.next().is_none() {
        return if sub == "status" { startup_status_all() } else { startup_off_all() };
    }
    let dir = match parse_dir(args) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("{e}");
            return 2;
        }
    };
    // absolute path — deriving the unit name from the instance dir must be stable (same instance, same name from any cwd)
    let dir = dir.canonicalize().unwrap_or(dir);
    match sub.as_str() {
        "on" => startup_install(&dir),
        "off" => startup_uninstall(&dir),
        _ => startup_status(&dir),
    }
}

/// `startup status` (no arg): full host-domain inventory (mirrors server startup_status_all).
fn startup_status_all() -> i32 {
    let (units, unknown) = startup_scan_health();
    let linger = startup_linger_enabled();
    for u in &unknown {
        eprintln!(
            "warning: unknown oxmgr unit: {u} (not product-named — to sweep manually: systemctl --user disable --now + rm)"
        );
    }
    if units.is_empty() {
        if unknown.is_empty() {
            let p = mediaservo_common::brand::media_brand().product;
            println!("no {p} autostart unit on this machine — enable with `{p} startup on <dir>`");
        }
        return 1;
    }
    let mut unhealthy = 0;
    for u in &units {
        let e = u.enabled.as_deref();
        let a = u.active.as_deref();
        for line in startup_status_line(&u.name, e, a, linger, u.bin_alive) {
            println!("{line}");
        }
        if !startup_unit_healthy(e, a, u.bin_alive) {
            unhealthy += 1;
        }
    }
    i32::from(unhealthy > 0)
}

/// `startup off` (no arg): zero = idempotent 0; exactly one = direct stop; many = tty list-and-pick / non-tty refuse.
fn startup_off_all() -> i32 {
    let (units, _unknown) = startup_scan_health();
    let tty = std::io::IsTerminal::is_terminal(&std::io::stdin());
    match startup_select_off(units.len(), tty) {
        S2OffSelect::NoneInstalled => {
            println!("startup off: autostart not installed");
            0
        }
        S2OffSelect::Single => startup_uninstall_unit(&units[0].name),
        S2OffSelect::Prompt => {
            for (i, u) in units.iter().enumerate() {
                println!("[{}] {} ({})", i + 1, u.name, u.active.as_deref().unwrap_or("?"));
            }
            println!("[0] uninstall all / enter = cancel");
            let mut ans = String::new();
            let _ = std::io::stdin().read_line(&mut ans);
            let picked: Vec<String> = match ans.trim() {
                "" => return 0,
                "0" => units.iter().map(|u| u.name.clone()).collect(),
                n => match n.parse::<usize>().ok().filter(|n| (1..=units.len()).contains(n)) {
                    Some(i) => vec![units[i - 1].name.clone()],
                    None => {
                        eprintln!("invalid selection: {n}");
                        return 2;
                    }
                },
            };
            let mut rc = 0;
            for name in picked {
                rc |= startup_uninstall_unit(&name);
            }
            rc
        }
        S2OffSelect::RejectList => {
            eprintln!(
                "startup off: this machine has multiple product autostart units; refusing a blind uninstall in a non-interactive environment — use `startup off <dir>` to target one:"
            );
            for u in &units {
                eprintln!("  {}", u.name);
            }
            1
        }
    }
}

/// Uninstall a single unit (disable --now + rm + daemon-reload).
fn startup_uninstall_unit(unit: &str) -> i32 {
    let _ =
        std::process::Command::new("systemctl").args(["--user", "disable", "--now", unit]).status();
    let _ = std::fs::remove_file(
        std::path::Path::new(&std::env::var("HOME").unwrap_or_default())
            .join(".config/systemd/user")
            .join(unit),
    );
    let _ = std::process::Command::new("systemctl").args(["--user", "daemon-reload"]).status();
    println!("startup off: stopped and removed {unit}");
    0
}

/// Autostart unit name (derived from the instance dir — each instance autostarts on its own, no overwrite contention by design)
fn startup_unit_name(dir: &std::path::Path) -> String {
    let raw = dir.to_string_lossy().replace(['/', '\\', ' '], "-");
    let raw = raw.trim_start_matches('-');
    // the default brand keeps the legacy "oxmgr-host-*" form (brand.rs mapping); branded is "oxmgr-<brand>-*"
    format!("{}{raw}.service", mediaservo_common::brand::media_brand().unit_prefix)
}

/// oxmgr binary path of the instance daemon (same dir as the host CLI)
fn oxmgr_path() -> std::path::PathBuf {
    std::env::current_exe()
        .ok()
        .and_then(|p| p.parent().map(|d| d.join("oxmgr")))
        .filter(|p| p.exists())
        .unwrap_or_else(|| std::path::PathBuf::from("oxmgr"))
}

#[cfg(target_os = "linux")]
fn startup_install(dir: &std::path::Path) -> i32 {
    // S1 v2 conflict gate: identity check + port comparison (shared resources like cameras — same-class collisions must be handled).
    // All decisions live in the s1_decide_v2 pure function; this does the scan IO + interactive execution only.
    let (conflicts, unknown) = startup_scan_conflicts(dir);
    for u in &unknown {
        eprintln!(
            "warning: unknown oxmgr unit detected (domain not recognized, left untouched): {u}"
        );
    }
    for c in &conflicts {
        eprintln!(
            "detected another autostart anchor of this product: unit={} instance={} domain={} conflicting ports={}",
            c.peer_unit,
            c.peer_dir.display(),
            match c.peer_kind {
                S1SameDomain => "same-class",
                S1CrossDomain => "cross-domain",
            },
            if c.overlapping.is_empty() {
                "none".to_string()
            } else {
                format!("{:?}", c.overlapping)
            }
        );
    }
    let tty = std::io::IsTerminal::is_terminal(&std::io::stdin());
    match s1_decide_v2(&conflicts, tty) {
        S1Abort => {
            eprintln!(
                "  non-interactive environment — exiting (port conflicts need handling; run `startup off <old dir>` first or take over interactively)"
            );
            return 1;
        }
        S1PromptTakeover => {
            eprintln!(
                "same-class instance port conflict — pick one: [1] skip install [2] uninstall the peer and take over [3] handle manually"
            );
            match s1_prompt().as_str() {
                "2" => {
                    for c in conflicts.iter().filter(|c| c.peer_kind == S1SameDomain) {
                        eprintln!(
                            "  takeover: uninstalling {} (instance {}, port details above)",
                            c.peer_unit,
                            c.peer_dir.display()
                        );
                        s1_takeover_peer(&c.peer_unit, &c.peer_dir);
                    }
                    let _ = std::process::Command::new("systemctl")
                        .args(["--user", "daemon-reload"])
                        .status();
                }
                "3" => {
                    eprintln!("exited — handle the conflicts above manually then retry");
                    return 1;
                }
                _ => {
                    println!("cancelled");
                    return 0;
                }
            }
        }
        S1PromptCrossDomainWarn => {
            eprintln!(
                "warning: cross-service-domain port overlap — different service domains, usually a misconfiguration"
            );
            eprintln!(
                "pick: [1] overwrite (uninstall peer) [2] cancel this one [3] allow parallel (risks acknowledged)"
            );
            match s1_prompt().as_str() {
                "1" => {
                    for c in conflicts
                        .iter()
                        .filter(|c| c.peer_kind == S1CrossDomain && !c.overlapping.is_empty())
                    {
                        eprintln!(
                            "  overwrite: uninstalling {} (instance {}, port details above)",
                            c.peer_unit,
                            c.peer_dir.display()
                        );
                        s1_takeover_peer(&c.peer_unit, &c.peer_dir);
                    }
                    let _ = std::process::Command::new("systemctl")
                        .args(["--user", "daemon-reload"])
                        .status();
                }
                "3" => {
                    eprintln!("warning: parallel allowed — port overlap risks acknowledged");
                }
                _ => {
                    println!("cancelled");
                    return 0;
                }
            }
        }
        S1Coexist(note) => {
            println!("startup on: {note}");
        }
        S1Install => {}
    }
    let unit_name = startup_unit_name(dir);
    let unit_path = std::path::Path::new(&std::env::var("HOME").unwrap_or_default())
        .join(".config/systemd/user")
        .join(&unit_name);
    // S5 field-corrigendum 2 (server same cut): systemd has no PATH — a bare ExecStart name = 203/EXEC crash loop.
    let oxmgr = {
        let p = oxmgr_path();
        if !p.is_absolute() {
            eprintln!(
                "startup on: cannot locate the absolute oxmgr path (no oxmgr beside bin/) — put it in place and retry"
            );
            return 1;
        }
        p
    };
    let data_dir = dir.join("run").join("oxmgr");
    // idempotent: overwrite own unit (rerunning on for the same instance = refresh)
    let unit = format!(
        "[Unit]
         Description=MediaServo host oxmgr daemon ({})
         After=network.target
         
         [Service]
         Type=simple
         Environment=OXMGR_HOME={}
         Environment=OXMGR_DAEMON_ADDR=127.0.0.1:{}
         Environment=OXMGR_API_ADDR=127.0.0.1:{}
         ExecStart={} daemon run
         Restart=always
         RestartSec=2
         
         [Install]
         WantedBy=default.target
",
        dir.display(),
        data_dir.display(),
        instance_daemon_port(dir),
        instance_daemon_port(dir) + 1000,
        oxmgr.display()
    );
    if let Some(parent) = unit_path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    if let Err(e) = std::fs::write(&unit_path, unit) {
        eprintln!("startup on: failed to write unit: {e}");
        return 1;
    }
    println!(
        "startup on: installed {} (OXMGR_DATA_DIR={})",
        unit_path.display(),
        data_dir.display()
    );
    for args in [
        vec!["systemctl", "--user", "daemon-reload"],
        vec!["systemctl", "--user", "enable", "--now", unit_name.as_str()],
    ] {
        let st = std::process::Command::new(args[0]).args(&args[1..]).status();
        match st {
            Ok(s) if s.success() => {}
            Ok(s) => {
                eprintln!(
                    "startup on: {} exited with code {}",
                    args.join(" "),
                    s.code().unwrap_or(-1)
                );
                return 1;
            }
            Err(e) => {
                eprintln!(
                    "startup on: failed to run {}: {e} (systemd user services unavailable?)",
                    args.join(" ")
                );
                return 1;
            }
        }
    }
    if !s3_probe_startup(&unit_name) {
        return 1;
    }
    println!("startup on: boot autostart enabled + daemon brought up ✓ ({unit_name})");
    // S5 field corrigendum (same cut as the server side): a daemon anchor does not raise the cluster — apply the oxfile to wake it idempotently.
    let oxfile = dir.join("run").join("oxfile.toml");
    if oxfile.exists() {
        println!("startup on: waking instance processes (apply {})", oxfile.display());
        if run_oxmgr_in(Some(dir), &["apply", &oxfile.to_string_lossy()]) != 0 {
            eprintln!(
                "startup on: apply failed — unit/daemon in place but the instance was not brought up (start manually: {})",
                dir.display()
            );
            return 1;
        }
    } else {
        eprintln!(
            "startup on: no {} (instance never init/started) — only the daemon anchor is in place",
            oxfile.display()
        );
    }
    println!("startup on: recommend loginctl enable-linger to survive across sessions");
    0
}

